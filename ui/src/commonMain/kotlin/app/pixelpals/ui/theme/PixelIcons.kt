/** Draws a [PixelIcon] crisply at [size], tinted with [tint] and [accent]. */
@Composable
fun PixelIconImage(
    icon: PixelIcon,
    modifier: Modifier = Modifier,
    size: Dp = 28.dp,
    tint: Color = LocalContentColor.current,
    accent: Color = MaterialTheme.colorScheme.secondary,
) {
    Canvas(modifier.size(size)) {
        val cell = minOf(this.size.width / icon.width, this.size.height / icon.height)
        val cellSize = Size(cell + 0.5f, cell + 0.5f)
        val ox = (this.size.width - cell * icon.width) / 2
        val oy = (this.size.height - cell * icon.height) / 2
        for (i in icon.cells.indices) {
            val color =
                when (icon.cells[i]) {
                    '#' -> tint
                    '+' -> accent
                    else -> continue
                }
            drawRect(color, Offset(ox + (i % icon.width) * cell, oy + (i / icon.width) * cell), cellSize)
        }
    }
}
